def get_preset(preset_id):
    """按 id 取一套人设；找不到返回 None。"""
    for p in PERSONA_PRESETS:
        if p.get("id") == preset_id:
            return p
    return None


def preset_to_persona(preset):
    """把一套预设转成 persona.json 里存的形状。"""
    stages = {}
    for key in ("1", "2", "3"):
        st = preset["stages"][key]
        stages[key] = {
            "name": st["name"],
            "description": st.get("description", ""),
            "prompt": st["prompt"],
        }
    return {"bot_profile": dict(preset["bot_profile"]), "stages": stages}



